"""Apply recorded human visual-review decisions after audit-anime-logos.py.

Only explicitly recorded self-generated resources can be replaced/removed;
checks their old hashes before touching them. Never changes the four overrides.
"""
import hashlib
import io
import json
from pathlib import Path
import importlib.util
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('audit', ROOT / 'scripts/audit-anime-logos.py')
audit = importlib.util.module_from_spec(spec)
spec.loader.exec_module(audit)


def main():
    registry = json.loads(audit.REGISTRY.read_text(encoding='utf-8'))
    report = json.loads(audit.REPORT.read_text(encoding='utf-8'))
    rows = {row['aniListId']: row for row in registry['logos']}
    entries = {row['aniListId']: row for row in report['entries']}
    decisions = json.loads((ROOT / 'docs/artwork/logo-review.json').read_text(encoding='utf-8'))['decisions']
    for decision in decisions:
        aid = decision['aniListId']
        entry = entries[aid]
        if entry.get('visualReview') == decision['reason']:
            continue
        old = rows.get(aid)
        destination = audit.ASSETS / f'anilist_{aid}.png'
        if old:
            assert destination.name == old['asset']
            assert hashlib.sha256(destination.read_bytes()).hexdigest() == old['sha256']
        if decision['action'] == 'reject':
            if old:
                destination.unlink()  # Exact file generated by this audit, hash-checked above.
                del rows[aid]
            entry['status'] = 'rejected-after-visual-review'
            entry.pop('asset', None)
        else:
            image = Image.open(io.BytesIO(audit.request(decision['source']))).convert('RGBA')
            alpha = image.getchannel('A')
            assert alpha.getextrema()[0] == 0 and alpha.getbbox()
            image = image.crop(alpha.getbbox())
            image.thumbnail((1200, 600), Image.Resampling.LANCZOS)
            assert image.width >= 200 and image.height >= 30
            padded = Image.new('RGBA', (image.width + 8, image.height + 8))
            padded.paste(image, (4, 4))
            padded.save(destination, optimize=True)
            if not old:
                mapping = [r for r in json.loads((audit.RESOURCES / 'series-mappings.json').read_text())['rows'] if str(r[0]) == aid]
                assert len(mapping) == 1
                old = {'aniListId': aid, 'tmdbId': str(mapping[0][1]), 'type': entry['type'], 'season': mapping[0][4],
                       'asset': destination.name, 'identityEvidence': 'official-second-season-site-and-existing-ID-mapping'}
            old |= {'source': decision['source'], 'sha256': hashlib.sha256(destination.read_bytes()).hexdigest(), 'visualReview': decision['reason']}
            if decision.get('sourcePage'):
                old['sourcePage'] = decision['sourcePage']
            rows[aid] = old
            entry |= {'status': 'added', 'source': decision['source'], 'asset': destination.name}
        entry['visualReview'] = decision['reason']
    registry['logos'] = sorted(rows.values(), key=lambda row: int(row['aniListId']))
    report['summary'] = {status: sum(e['status'] == status for e in report['entries']) for status in sorted({e['status'] for e in report['entries']})}
    audit.REGISTRY.write_text(json.dumps(registry, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    audit.REPORT.write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(report['summary'])


if __name__ == '__main__':
    main()
